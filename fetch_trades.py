BIOGUIDE_FILE = Path(__file__).parent / "member_bioguide.json"


def load_bioguide_directory() -> dict:
    """
    Load member_bioguide.json and return a lookup dict keyed by bioguide ID.
    Each entry exposes the most recent term so callers can resolve party,
    chamber, and state without scraping capitoltrades.
    """
    if not BIOGUIDE_FILE.exists():
        return {}
    try:
        with open(BIOGUIDE_FILE, "r", encoding="utf-8") as f:
            records = json.load(f)
    except Exception as exc:
        print(f"  ! Could not load {BIOGUIDE_FILE.name}: {exc}")
        return {}

    lookup: dict = {}
    for rec in records:
        bid = (rec.get("id") or {}).get("bioguide")
        if not bid:
            continue
        name = rec.get("name") or {}
        terms = rec.get("terms") or []
        last_term = terms[-1] if terms else {}
        chamber_raw = (last_term.get("type") or "").lower()
        chamber = "Senate" if chamber_raw == "sen" else "House" if chamber_raw == "rep" else ""
        lookup[bid] = {
            "bioguideId": bid,
            "firstName":  name.get("first", ""),
            "lastName":   name.get("last", ""),
            "fullName":   name.get("official_full") or f"{name.get('first','')} {name.get('last','')}".strip(),
            "party":      last_term.get("party", ""),
            "state":      last_term.get("state", ""),
            "chamber":    chamber,
        }
    return lookup


def resolve_politician_id(query: str, directory: dict) -> str | None:
    """Resolve a bioguide ID or a member name (case-insensitive) to a bioguide ID."""
    if not query:
        return None
    if query in directory:
        return query
    q = query.strip().lower()
    for bid, info in directory.items():
        if info["fullName"].lower() == q:
            return bid
    # last-name fallback (only if unique)
    matches = [bid for bid, info in directory.items() if info["lastName"].lower() == q]
    if len(matches) == 1:
        return matches[0]
    return None


BASE_URL = "https://www.capitoltrades.com/trades"
PAGE_SIZE = 96          # max the site supports
DELAY_SECS = 1.5        # polite delay between requests

