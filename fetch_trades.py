def main():
    parser = argparse.ArgumentParser(description="Fetch congressional trade data from capitoltrades.com")
    parser.add_argument("--days", type=int, default=60,
                        help="Lookback window in days (default: 60)")
    parser.add_argument("--out", default="trade_data",
                        help="Output filename prefix (default: trade_data)")
    parser.add_argument("--committee", default=None,
                        help="Committee name or thomas_id (e.g. 'House Committee on Armed Services' or 'HSAS'). "
                             "Overrides POLITICIAN_IDS and any IDs passed positionally.")
    parser.add_argument("ids", nargs="*",
                        help="Politician IDs to fetch (overrides the POLITICIAN_IDS list in the script)")
    args = parser.parse_args()

    # Load the local bioguide directory once; used for name→ID resolution
    # and as a metadata fallback when the scraper can't extract member info.
    directory = load_bioguide_directory()
    if directory:
        print(f"Loaded {len(directory)} members from {BIOGUIDE_FILE.name}")

    # Priority: --committee > positional IDs > hardcoded POLITICIAN_IDS.
    committee_summary = None
    if args.committee:
        from committee_lookup import describe_committee, resolve_committee
        committee_summary = describe_committee(args.committee)
        if not committee_summary or not committee_summary["bioguideIds"]:
            res = resolve_committee(args.committee)
            candidates = res.get("candidates", [])
            if candidates:
                print(f"ERROR: '{args.committee}' matched {len(candidates)} committees:")
                for c in candidates:
                    print(f"  {c.get('thomas_id','????'):<6} {c.get('name','')}")
                print("Re-run with the full committee name or thomas_id to disambiguate.")
            else:
                print(f"ERROR: Could not resolve committee '{args.committee}'.")
                print("Run `python3 committee_lookup.py --list` to see all committees.")
            sys.exit(2)
        print(f"Committee: {committee_summary['name']} ({committee_summary['thomas_id']}) — "
              f"{committee_summary['memberCount']} members")
        raw_inputs = committee_summary["bioguideIds"]
    else:
        raw_inputs = args.ids if args.ids else POLITICIAN_IDS

    # Naming: when a committee is used, embed its slug in the output prefix
    # so downstream artifacts don't collide with the default-list run.
    # Otherwise fall back to whatever was passed via --out (default "trade_data").
    if committee_summary and args.out == "trade_data":
        slug = re.sub(r"[^a-z0-9]+", "_", committee_summary["name"].lower()).strip("_")
        args.out = f"trade_data_{slug}"
        print(f"Output prefix: {args.out}")

    # CLI arguments may be either bioguide IDs or member names — resolve via the directory.
    ids_to_fetch: list[str] = []
    for entry in raw_inputs:
        resolved = resolve_politician_id(entry, directory) if directory else None
        if resolved:
            ids_to_fetch.append(resolved)
        else:
            # Pass through unchanged; assume caller supplied a bioguide ID
            ids_to_fetch.append(entry)
    if not ids_to_fetch:
        print("ERROR: No politician IDs provided.")
        print("Either add IDs to the POLITICIAN_IDS list in the script, or pass them as arguments:")
        print("  python fetch_trades.py F000110 K000389 P000197")
        sys.exit(1)

    cutoff = date.today() - timedelta(days=args.days)
    print(f"Fetching {args.days}-day trade window (since {cutoff}) for {len(ids_to_fetch)} member(s):")
    for pid in ids_to_fetch:
        print(f"  • {pid}")

    members: dict = {}
    for politician_id in ids_to_fetch:
        try:
            result = fetch_member_trades(politician_id, cutoff, directory)
            name_key = result["fullName"] or politician_id
            members[name_key] = result
            print(f"  ✓ {name_key}: {result['tradeCount']} trades in window")
        except Exception as exc:
            print(f"  ✗ {politician_id}: {exc}")
        time.sleep(DELAY_SECS)

    output = {
        "metadata": {
            "generated":       date.today().isoformat(),
            "window_days":     args.days,
            "cutoff_date":     cutoff.isoformat(),
            "source":          "capitoltrades.com",
            "members_tracked": len(members),
            "committee":       (
                {
                    "name":      committee_summary["name"],
                    "thomas_id": committee_summary["thomas_id"],
                }
                if committee_summary else None
            ),
        },
        "members": members,
    }

    from datetime import datetime
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")

    data_dir = Path(__file__).parent / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    # Current file (overwritten each run — used by the analysis pipeline)
    write_json(output, data_dir / f"{args.out}.json")

    # Timestamped archive copy in data/ (used by change detection)
    write_json(output, data_dir / f"{args.out}_{ts}.json")

    # Summary table
    print("\n" + "─" * 60)
    print(f"{'Member':<30} {'Party':<12} {'Trades':>6}")
    print("─" * 60)
    for name, d in members.items():
        print(f"{name:<30} {d.get('party',''):<12} {d['tradeCount']:>6}")
    print("─" * 60)
    total = sum(d["tradeCount"] for d in members.values())
    print(f"{'TOTAL':<43} {total:>6}")
    print()

    # Hint for downstream pipeline so the agent knows which file to feed in.
    stats_out = args.out.replace("trade_data", "computed_stats")
    skel_out  = args.out.replace("trade_data", "analysis_skeleton")
    anly_out  = args.out.replace("trade_data", "analysis")
    print("Next steps:")
    print(f"  python3 compute_analysis.py --in data/{args.out}.json --out computed_stats/{stats_out}.json")
    print(f"  python3 build_skeleton.py    --in computed_stats/{stats_out}.json --out analysis_skeleton/{skel_out}.json")
    print(f"  # then fill placeholders into analysis/{anly_out}.json and:")
    print(f"  python3 generate_report.py analysis/{anly_out}.json")
    print()


if __name__ == "__main__":
    main()
