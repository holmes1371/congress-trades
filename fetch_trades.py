def _fetch_page(politician_id: str, page: int) -> str:
    """Fetch one page of trade results and return the raw HTML."""
    url = (
        f"{BASE_URL}?politician={politician_id}"
        f"&pageSize={PAGE_SIZE}&page={page}"
    )
    response = requests.get(url, headers=HEADERS, timeout=20)
    response.raise_for_status()
    return response.text


def _normalise_trade(raw: dict) -> dict:
    """Convert a raw RSC trade object into our clean schema."""
    issuer = raw.get("issuer") or {}
    return {
        "txId":           raw.get("_txId"),
        "company":        issuer.get("issuerName"),
        "ticker":         issuer.get("issuerTicker"),
        "sector":         issuer.get("sector"),
        "txDate":         raw.get("txDate"),           # "YYYY-MM-DD"
        "published":      raw.get("pubDate", "")[:10], # truncate to date
        "filedAfterDays": raw.get("reportingGap"),
        "type":           (raw.get("txType") or "").upper(),
        "typeExtended":   raw.get("txTypeExtended"),
        "value":          raw.get("value"),             # mid-point $ estimate
        "price":          raw.get("price"),
        "owner":          raw.get("owner"),
        "comment":        raw.get("comment"),
    }


def fetch_member_trades(politician_id: str, cutoff_date: date, directory: dict | None = None) -> dict:
    """
    Fetch all trades for *politician_id* on or after *cutoff_date*.

    Returns a dict:
        {
            "bioguideId": str,
            "firstName": str,  "lastName": str,
            "chamber": str,    "state": str,    "party": str,
            "tradeCount": int,
            "trades": [...]
        }
    """
    print(f"\n  Fetching {politician_id}…", flush=True)
    all_trades: list[dict] = []
    total_pages = None
    member_info: dict = {}

    page = 1
    while True:
        print(f"    page {page}", end="")
        try:
            html = _fetch_page(politician_id, page)
        except requests.HTTPError as exc:
            print(f"  HTTP {exc.response.status_code} — stopping.")
            break

        chunks = _extract_rsc_chunks(html)

        # First page: capture member metadata and pagination
        if page == 1:
            member_info = _parse_member_info(chunks)
            pagination  = _parse_pagination(chunks)
            total_pages = pagination["totalPages"]
            total_count = pagination["totalCount"]
            print(f"  ({total_count} total trades, {total_pages} pages)", flush=True)
        else:
            print("", flush=True)

        raw_trades = []
        for chunk in chunks:
            raw_trades = _parse_trades_from_chunk(chunk)
            if raw_trades:
                break

        if not raw_trades:
            print("    No trades parsed on this page — stopping.")
            break

        # Normalise and filter to cutoff window
        stop_early = False
        for raw in raw_trades:
            tx_date_str = raw.get("txDate") or ""
            if tx_date_str:
                tx_date = date.fromisoformat(tx_date_str)
                if tx_date < cutoff_date:
                    stop_early = True
                    # Don't break — this page might have mixed dates;
                    # skip only trades older than cutoff
                    continue
            all_trades.append(_normalise_trade(raw))

        if stop_early:
            print("    Hit cutoff date — no need to fetch further pages.")
            break

        if page >= total_pages:
            break

        page += 1
        time.sleep(DELAY_SECS)

    # Sort by trade date descending
    all_trades.sort(key=lambda t: t["txDate"] or "", reverse=True)

    # Fall back to the local bioguide directory for any missing metadata.
    directory = directory or {}
    bio_info = directory.get(politician_id, {})
    for key in ("firstName", "lastName", "chamber", "state", "party"):
        if not member_info.get(key) and bio_info.get(key):
            member_info[key] = bio_info[key]

    full_name = (
        f"{member_info.get('firstName', '')} {member_info.get('lastName', '')}".strip()
        or bio_info.get("fullName")
        or politician_id
    )
    return {
        "bioguideId": politician_id,
        "fullName":   full_name,
        **member_info,
        "tradeCount": len(all_trades),
        "trades":     all_trades,
    }


