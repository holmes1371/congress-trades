# RSC PARSING
# ── ── ── ── ── ── ── ── ── ── ── ── ── ── ── ── ── ── ── ──

def _extract_rsc_chunks(html: str) -> list[str]:
    """Return all decoded RSC payload strings from the page HTML."""
    chunks = []
    for m in re.finditer(
        r'self\.__next_f\.push\(\[(\d+),(".*?"|\[.*?\])\]\)',
        html,
        re.DOTALL,
    ):
        try:
            chunks.append(json.loads(m.group(2)))
        except Exception:
            pass
    return chunks


def _parse_trades_from_chunk(chunk: str) -> list[dict]:
    """
    Extract the raw trade objects from a single RSC chunk string.
    Returns an empty list if this chunk contains no trade data.
    """
    if '"_txId"' not in chunk:
        return []

    # The trade records sit inside a "data":[...] array within the RSC JSON tree.
    pos = chunk.find('"_txId"')
    start = chunk.rfind("[{", 0, pos)
    if start < 0:
        return []

    # Walk forward to find the closing ]} of the data array.
    depth = 0
    end = start
    for i, ch in enumerate(chunk[start:], start=start):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                end = i + 1
                # Check if next non-space char closes the array
                rest = chunk[end:].lstrip()
                if rest.startswith("]"):
                    end = chunk.index("]", end) + 1
                    break

    raw = chunk[start:end]
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        # Attempt a lenient fallback using regex to pull individual objects
        objects = re.findall(r'\{[^{}]*"_txId"[^{}]*\}', raw)
        results = []
        for obj in objects:
            try:
                results.append(json.loads(obj))
            except Exception:
                pass
        return results


def _parse_pagination(chunks: list[str]) -> dict:
    """Extract totalCount and totalPages from any RSC chunk."""
    for chunk in chunks:
        if "totalPages" in chunk:
            m = re.search(r'"totalCount":(\d+),"totalPages":(\d+)', chunk)
            if m:
                return {
                    "totalCount": int(m.group(1)),
                    "totalPages": int(m.group(2)),
                }
    return {"totalCount": 0, "totalPages": 1}


def _parse_member_info(chunks: list[str]) -> dict:
    """Pull the politician name/party/chamber/state from the first page chunks."""
    for chunk in chunks:
        if '"_txId"' in chunk:
            m = re.search(
                r'"politician":\{"_stateId":"(?P<state>[^"]+)",'
                r'"chamber":"(?P<chamber>[^"]+)",'
                r'[^}]*"firstName":"(?P<first>[^"]+)",'
                r'[^}]*"lastName":"(?P<last>[^"]+)",'
                r'[^}]*"party":"(?P<party>[^"]+)"',
                chunk,
            )
            if m:
                return {
                    "firstName": m.group("first"),
                    "lastName": m.group("last"),
                    "chamber": m.group("chamber").title(),
                    "state": m.group("state").upper(),
                    "party": m.group("party").title(),
                }
    return {}


